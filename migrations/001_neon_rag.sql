-- 3alimnIA RAG V0.3: run ONLY on a separate Neon staging branch/database.
-- Explicit migration: the Streamlit app never executes schema DDL.
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS rag_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner TEXT NOT NULL CHECK (length(trim(owner)) > 0),
    project_id BIGINT NOT NULL CHECK (project_id > 0),
    source_id TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    origin TEXT NOT NULL CHECK (origin IN ('teacher', 'external')),
    approved BOOLEAN NOT NULL DEFAULT FALSE,
    license_note TEXT NOT NULL DEFAULT '',
    content_sha256 CHAR(64) NOT NULL,
    cloud_processing_consent BOOLEAN NOT NULL DEFAULT FALSE,
    cloud_generation_consent BOOLEAN NOT NULL DEFAULT FALSE,
    embedding_provider TEXT NOT NULL DEFAULT 'lexical',
    embedding_model TEXT NOT NULL DEFAULT '',
    approved_by TEXT NOT NULL DEFAULT '',
    approved_at TIMESTAMPTZ,
    source_url TEXT NOT NULL DEFAULT '',
    citation_label TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (owner, project_id, content_sha256)
);

CREATE INDEX IF NOT EXISTS rag_documents_scope_idx
    ON rag_documents (owner, project_id, approved, origin);

CREATE TABLE IF NOT EXISTS rag_chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES rag_documents(id) ON DELETE CASCADE,
    page INTEGER,
    ordinal INTEGER NOT NULL CHECK (ordinal > 0),
    body TEXT NOT NULL,
    vector_gemini VECTOR(768),
    UNIQUE (document_id, ordinal)
);

CREATE INDEX IF NOT EXISTS rag_chunks_document_idx ON rag_chunks (document_id);
CREATE INDEX IF NOT EXISTS rag_chunks_lexical_idx
    ON rag_chunks USING GIN (to_tsvector('simple', body));
CREATE INDEX IF NOT EXISTS rag_chunks_vector_gemini_hnsw_idx
    ON rag_chunks USING hnsw (vector_gemini vector_cosine_ops)
    WHERE vector_gemini IS NOT NULL;

-- The log records decisions only; never store source text or API keys here.
CREATE TABLE IF NOT EXISTS rag_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner TEXT NOT NULL,
    project_id BIGINT NOT NULL,
    source_id TEXT NOT NULL,
    action TEXT NOT NULL CHECK (action IN
        ('indexed', 'approved', 'revoked', 'cloud_generation_allowed',
         'cloud_generation_revoked', 'cloud_embedding_allowed',
         'cloud_embedding_revoked', 'deleted')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS rag_events_scope_idx
    ON rag_events (owner, project_id, created_at DESC);
